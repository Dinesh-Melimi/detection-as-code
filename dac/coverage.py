"""Generate a MITRE ATT&CK coverage report (Markdown) from the rule set.

Output is deterministic (sorted, no timestamps) so the committed report only
changes when rules change, and CI can diff it.
"""

from __future__ import annotations

from collections import defaultdict

from . import attack
from .rules import LoadedRule


def build_index(rules: list[LoadedRule]) -> dict[str, list[LoadedRule]]:
    index: dict[str, list[LoadedRule]] = defaultdict(list)
    for rule in rules:
        for tech in attack.techniques_from_tags(rule.data["tags"]):
            index[tech].append(rule)
    return dict(index)


def render_markdown(rules: list[LoadedRule]) -> str:
    index = build_index(rules)
    by_tactic: dict[str, list[str]] = defaultdict(list)
    for tech in sorted(index):
        for tactic in attack.TECHNIQUES[tech][1]:
            by_tactic[tactic].append(tech)

    covered_tactics = [t for t in attack.TACTICS if by_tactic.get(t)]
    lines = [
        "# ATT&CK Coverage Report",
        "",
        "_Generated by `python -m dac coverage`. Do not edit by hand._",
        "",
        f"- Rules: **{len(rules)}**",
        f"- Techniques / sub-techniques covered: **{len(index)}**",
        f"- Tactics with at least one detection: **{len(covered_tactics)} / {len(attack.TACTICS)}**",
        "",
        "Coverage here means *a rule exists and passes its sample tests*, not that",
        "the technique is fully detected in every variant. Treat it as a map of",
        "where to look for gaps, not a score.",
        "",
        "## Matrix",
        "",
        "| Tactic | Techniques | Rules |",
        "|---|---|---|",
    ]
    for tactic in attack.TACTICS:
        techs = by_tactic.get(tactic, [])
        if techs:
            cell = "<br>".join(f"{t} {attack.TECHNIQUES[t][0]}" for t in techs)
            count = len({r.name for t in techs for r in index[t]})
        else:
            cell, count = "_no coverage_", 0
        lines.append(f"| {tactic} | {cell} | {count} |")

    lines += ["", "## Techniques", "", "| Technique | Name | Rules |", "|---|---|---|"]
    for tech in sorted(index):
        rule_list = ", ".join(f"`{r.name}`" for r in sorted(index[tech], key=lambda r: r.name))
        lines.append(f"| {tech} | {attack.TECHNIQUES[tech][0]} | {rule_list} |")

    lines += ["", "## Rules", "", "| Rule | Level | Status | Log source | Techniques |",
              "|---|---|---|---|---|"]
    for rule in sorted(rules, key=lambda r: r.name):
        d = rule.data
        src = f"{d['logsource']['product']}/{d['logsource'].get('category') or d['logsource'].get('service')}"
        techs = ", ".join(attack.techniques_from_tags(d["tags"]))
        lines.append(f"| {d['title']} | {d['level']} | {d['status']} | {src} | {techs} |")
    return "\n".join(lines) + "\n"
